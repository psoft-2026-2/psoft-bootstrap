public class Endereco{
    private String rua;
    private String bairro;
    private String cidade;
    private String number;

    public Endereco(String bairro, String cidade, String number, String rua) {
        this.bairro = bairro;
        this.cidade = cidade;
        this.number = number;
        this.rua = rua;
    }


}