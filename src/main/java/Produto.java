/**
 * Produto
 */
public class Produto {
    private String nome; 
    private int numeracao;
    
    public Produto(String nome, int numeracao) {
        this.nome = nome;
        this.numeracao = numeracao;
    }

    public String getNome() {
        return nome;
    }

   

    public int getNumeracao() {
        return numeracao;
    }

   
    

    

}
